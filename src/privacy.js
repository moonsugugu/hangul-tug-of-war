const el = (tag, text) => { const node = document.createElement(tag); if (text) node.textContent = text; return node; };
const list = (rows) => { const ul = el('ul'); rows.forEach((row) => ul.append(row)); return ul; };

/** 처리방침 칸을 한 번만 만들어 #app 아래(화면 맨 아래)에 붙인다. 화면을 다시 그려도 펼친 상태가 유지된다. */
export function mountPrivacy() {
  const section = el('section');
  section.className = 'privacy-policy';
  const details = el('details');
  details.id = 'privacy';
  const summary = el('summary', '학교용 SW 보안 및 개인정보보호 준수 안내');
  summary.append(el('small', '개인정보 처리방침'));
  const cards = el('div');
  cards.className = 'privacy-cards';
  for (const [title, rows] of CARDS) {
    const card = el('div');
    card.append(el('h3', title), list(rows.map(([label, text]) => { const li = el('li'); li.append(el('b', `${label}:`), ` ${text}`); return li; })));
    cards.append(card);
  }
  details.append(summary, cards, el('h3', '말모이 줄다리기 개인정보 처리방침'));
  for (const [head, text, subs] of ARTICLES) {
    const p = el('p');
    p.append(el('b', head), text ? ` ${text}` : '');
    details.append(p);
    if (subs.length) details.append(list(subs.map((sub) => el('li', sub))));
  }
  section.append(details);
  document.body.append(section);
  return section;
}

/** 주소 끝 #privacy 로 들어오면 처리방침을 펼치고 그 자리로 간다. */
export function openPrivacy() {
  const details = document.getElementById('privacy');
  if (location.hash !== '#privacy' || !details || details.parentElement.hidden) return;
  details.open = true;
  details.scrollIntoView();
}
